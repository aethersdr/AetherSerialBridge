#!/usr/bin/env python3
"""Generates src/tui/LogoArt.inc, the TUI's logo (master section 6, WS-12 "Logo pipeline").

Reads vendor/aethersdr/docs/assets/logo-circle.png (the vendored AetherSDR logo) and writes three renderings:

  - TrueColor half-blocks: 32 x 16 cells, i.e. 32 x 32 pixels, each cell a pixel pair drawn with an upper half
    block (foreground = upper pixel, background = lower pixel). A pixel with alpha below 50 % is transparent:
    the cell keeps the screen's background there.
  - The same pixels as xterm-256 colour indexes (16-255: the 6x6x6 cube and the grey ramp; 0-15 are left out
    because terminals redefine them), nearest by squared RGB distance, ties to the lower index.
  - An ASCII ramp of 24 x 12 cells for NO_COLOR, 16-colour and non-UTF-8 consoles.

Deterministic: Pillow's LANCZOS filter at a pinned Pillow version (the filter's output can change between
releases, so another version refuses to run), the fixed quantiser above, and no timestamps in the output.

  tools/gen_logo_art.py            write src/tui/LogoArt.inc
  tools/gen_logo_art.py --check    exit 1 when the committed file differs from what this would write (CI)
"""

import argparse
import hashlib
import os
import sys

PILLOW_VERSION = "11.0.0"

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SOURCE = "vendor/aethersdr/docs/assets/logo-circle.png"
OUTPUT = "src/tui/LogoArt.inc"

CELLS_WIDE, CELLS_HIGH = 32, 16          # half-block art: 32 x 32 pixels
ASCII_WIDE, ASCII_HIGH = 24, 12
ALPHA_MIN = 128                          # alpha < 50 % is transparent
RAMP = " .:-=+*#%@"                      # dark to dense, for a dark background


def xterm256():
    """The xterm-256 palette entries 16-255 as (index, (r, g, b))."""
    levels = [0, 95, 135, 175, 215, 255]
    out = []
    for i in range(216):
        out.append((16 + i, (levels[i // 36], levels[(i // 6) % 6], levels[i % 6])))
    for i in range(24):
        v = 8 + 10 * i
        out.append((232 + i, (v, v, v)))
    return out


PALETTE = xterm256()


def nearest256(rgb):
    best, best_d = None, None
    for index, (r, g, b) in PALETTE:
        d = (rgb[0] - r) ** 2 + (rgb[1] - g) ** 2 + (rgb[2] - b) ** 2
        if best_d is None or d < best_d:
            best, best_d = index, d
    return best


def ramp_char(rgba):
    r, g, b, a = rgba
    if a < ALPHA_MIN:
        return " "
    y = (299 * r + 587 * g + 114 * b) // 1000
    # An opaque pixel is never blank, so the disc keeps its outline on a dark screen.
    return RAMP[max(1, (y * (len(RAMP) - 1) + 127) // 255)]


def render(image_module, data):
    from io import BytesIO

    src = image_module.open(BytesIO(data)).convert("RGBA")
    lanczos = image_module.Resampling.LANCZOS
    px = src.resize((CELLS_WIDE, CELLS_HIGH * 2), lanczos)
    asc = src.resize((ASCII_WIDE, ASCII_HIGH), lanczos)

    true_color, pal256 = [], []
    for y in range(CELLS_HIGH * 2):
        for x in range(CELLS_WIDE):
            r, g, b, a = px.getpixel((x, y))
            if a < ALPHA_MIN:
                true_color.append(-1)
                pal256.append(-1)
            else:
                true_color.append((r << 16) | (g << 8) | b)
                pal256.append(nearest256((r, g, b)))
    ascii_rows = ["".join(ramp_char(asc.getpixel((x, y))) for x in range(ASCII_WIDE)) for y in range(ASCII_HIGH)]

    def rows(values, fmt, per_row):
        lines = []
        for i in range(0, len(values), per_row):
            lines.append("    " + ", ".join(fmt(v) for v in values[i:i + per_row]) + ",")
        return "\n".join(lines)

    hexrgb = lambda v: "-1" if v < 0 else "0x%06x" % v
    digest = hashlib.sha256(data).hexdigest()
    out = []
    out.append("// Generated by tools/gen_logo_art.py from %s" % SOURCE)
    out.append("// (sha256 %s) with Pillow %s. Do not edit: run the script; --check verifies." % (digest, PILLOW_VERSION))
    out.append("// Included once, by src/tui/Logo.cpp.")
    out.append("")
    out.append("namespace asb::tui::logo_art {")
    out.append("")
    out.append("inline constexpr int kCellsWide = %d;" % CELLS_WIDE)
    out.append("inline constexpr int kCellsHigh = %d;   // two pixels per cell" % CELLS_HIGH)
    out.append("")
    out.append("// %d x %d pixels, row-major: 0xRRGGBB, or -1 where alpha < 50 %% (transparent)." % (CELLS_WIDE, CELLS_HIGH * 2))
    out.append("inline constexpr int kTrueColor[%d] = {" % len(true_color))
    out.append(rows(true_color, hexrgb, 8))
    out.append("};")
    out.append("")
    out.append("// The same pixels as xterm-256 indexes (16-255), or -1 where transparent.")
    out.append("inline constexpr short kPalette256[%d] = {" % len(pal256))
    out.append(rows(pal256, str, 16))
    out.append("};")
    out.append("")
    out.append("inline constexpr int kAsciiWide = %d;" % ASCII_WIDE)
    out.append("inline constexpr int kAsciiHigh = %d;" % ASCII_HIGH)
    out.append("// Ramp \"%s\" by luminance; a space where transparent." % RAMP)
    out.append("inline constexpr const char* kAscii[%d] = {" % ASCII_HIGH)
    for row in ascii_rows:
        out.append('    "%s",' % row.replace("\\", "\\\\").replace('"', '\\"'))
    out.append("};")
    out.append("")
    out.append("}  // namespace asb::tui::logo_art")
    return ("\n".join(out) + "\n").encode("ascii")


def main():
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--check", action="store_true", help="compare with the committed file instead of writing it")
    args = ap.parse_args()
    try:
        import PIL
        from PIL import Image
    except ImportError:
        print("gen_logo_art.py: needs Pillow %s (pip install Pillow==%s)" % (PILLOW_VERSION, PILLOW_VERSION),
              file=sys.stderr)
        return 2
    if PIL.__version__ != PILLOW_VERSION:
        print("gen_logo_art.py: needs Pillow %s exactly (found %s): LANCZOS output may differ between releases"
              % (PILLOW_VERSION, PIL.__version__), file=sys.stderr)
        return 2
    with open(os.path.join(ROOT, SOURCE), "rb") as f:
        data = f.read()
    text = render(Image, data)
    target = os.path.join(ROOT, OUTPUT)
    if args.check:
        try:
            with open(target, "rb") as f:
                current = f.read()
        except FileNotFoundError:
            current = b""
        if current != text:
            print("gen_logo_art.py: %s is not what %s generates; run tools/gen_logo_art.py" % (OUTPUT, SOURCE),
                  file=sys.stderr)
            return 1
        print("gen_logo_art.py: %s is up to date" % OUTPUT)
        return 0
    with open(target, "wb") as f:
        f.write(text)
    print("gen_logo_art.py: wrote %s" % OUTPUT)
    return 0


if __name__ == "__main__":
    sys.exit(main())
